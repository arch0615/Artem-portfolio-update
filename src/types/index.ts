export interface NavItem {
  /** Section element id on the home page. */
  id: string
  label: string
}

export interface PortraitMedia {
  alt: string
  /** Intrinsic size of the still image. */
  width: number
  height: number
  /** The still image in several widths, smallest first: placeholder, fallback and reduced-motion view. */
  images: { src: string; width: number }[]
  /**
   * Optional muted looping clip, the primary visual when set. The frame takes the clip's aspect
   * ratio, so the clip is shown whole; the still image is cropped to it (background only).
   */
  video?: {
    width: number
    height: number
    /** In order of preference. */
    sources: { src: string; type: string }[]
  }
}

export interface Highlight {
  label: string
  icon: IconName
}

/**
 * How a technology's icon is drawn in the Skills section. Logos come from
 * `src/lib/tech-logos.ts` (generated by `npm run logos`).
 */
export type TechnologyIcon =
  /**
   * A single-colour official mark, filled with `color`: the brand colour, or the brand's
   * official white variant where the mark is black.
   */
  | { type: 'mono'; logo: MonoLogoKey; color: string }
  /** An official multicolour logo, drawn in its own colours. `color` is the primary brand colour. */
  | { type: 'multicolor'; logo: MulticolorLogoKey; color: string }
  /** A capability with no official logo: a Lucide icon in the portfolio accent colour. */
  | { type: 'generic'; icon: IconName }

export interface Technology {
  name: string
  icon: TechnologyIcon
}

export interface SkillCategory {
  id: string
  title: string
  /** Small icon beside the category name. */
  icon: IconName
  technologies: Technology[]
}

export interface Service {
  id: string
  title: string
  description: string
  icon: IconName
  items: string[]
}

/** A calendar month, written `YYYY-MM` (for example `2020-11`). */
export type YearMonth = `${number}-${number}`

/** One position in the Experience timeline (`src/data/experience.ts`). */
export interface Position {
  /** Stable key, e.g. the company's name in lowercase. */
  id: string
  company: string
  role: string
  /** First and last month in the role; `end: 'present'` for a current role. */
  start: YearMonth
  end: YearMonth | 'present'
  location: string
  summary: string
  /** Key responsibilities and achievements. */
  highlights: string[]
  technologies: string[]
}

/** Original CSS-based product mockups in `src/components/visuals`. */
export type ProjectVisualKey =
  | 'radar'
  | 'email'
  | 'django'
  | 'nexa'
  | 'solidhouse'
  | 'dourasoft'
  | 'style4u'
  | 'byd'

export type AccentTone = 'indigo' | 'violet' | 'sky' | 'emerald' | 'amber' | 'rose' | 'cyan' | 'fuchsia'

export interface ProjectLink {
  label: string
  href: string
}

export interface ProjectMetric {
  label: string
  value: string
  detail?: string
}

export interface Project {
  slug: string
  name: string
  category: string
  description: string
  technologies: string[]
  /** Third-party services the project integrates with. */
  integrations?: string[]
  features: string[]
  contribution?: string
  /** A verified, real result. Never add estimates here. */
  metric?: ProjectMetric
  links?: ProjectLink[]
  visual: ProjectVisualKey
  /** Short description of the mockup for screen readers. */
  visualLabel: string
  accent: AccentTone
  featured?: boolean
}

export interface CaseStudyItem {
  title: string
  description: string
}

export interface ArchitectureLayer {
  label: string
  title: string
  items: string[]
}

export interface CaseStudy {
  slug: string
  /** Meta description used for SEO and social previews. */
  seoDescription: string
  role: string
  overview: string
  problem: string
  challenges: CaseStudyItem[]
  architecture: {
    caption: string
    layers: ArchitectureLayer[]
  }
  stack: { group: string; items: string[] }[]
  implementation: CaseStudyItem[]
  decisions: CaseStudyItem[]
  results: {
    summary: string
    metrics?: ProjectMetric[]
    points: string[]
  }
}
